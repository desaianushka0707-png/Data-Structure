Data Structures – Searching

This repository contains my Data Structures practice programs in C, currently focusing on searching techniques.

📚 Programs Included

1. Linear Search

Linear Search checks each element one by one until the required element is found.

Time Complexity: O(n)

2. Binary Search

Binary Search repeatedly divides a sorted array into two halves to find the required element.

Time Complexity: O(log n)

